const icons: Record<
  SocialPlatformId,
  (props: { className?: string }) => ReactNode
> = {
  instagram: InstagramIcon,
  youtube: YoutubeIcon,
  tiktok: TikTokIcon,
  facebook: FacebookIcon,
};

export function SocialPlatformIcon({
  platform,
  className,
}: {
  platform: SocialPlatformId;
  className?: string;
}) {
  const Icon = icons[platform];
  return <Icon className={className} />;
}

export function SocialIconLinks({
  platforms,
  className,
  iconClassName,
}: {
  platforms: { id: SocialPlatformId; url: string }[];
  className?: string;
  iconClassName?: string;
}) {
  if (!platforms.length) return null;

  return (
    <div className={cn("flex items-center gap-2", className)}>
      {platforms.map((platform) => (
        <a
          key={platform.id}
          href={platform.url}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={SOCIAL_PLATFORM_LABELS[platform.id]}
          className="inline-flex h-9 w-9 items-center justify-center rounded-lg bg-surface-container-high text-on-surface transition-colors hover:bg-primary-container hover:text-on-primary-container"
        >
          <SocialPlatformIcon
            platform={platform.id}
            className={cn("h-5 w-5", iconClassName)}
          />
        </a>
      ))}
    </div>
  );
}
